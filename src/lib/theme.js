// Builds the small stylesheet that applies the user's accent colour and pill darkness on top of
// stylesheet.css. Pure: runs under node --test, and the preferences window uses it too.

export const DEFAULT_ACCENT = '#7aa2f7';
export const DEFAULT_PILL_OPACITY = 62;
export const MIN_PILL_OPACITY = 20;
export const MAX_PILL_OPACITY = 100;

// Tokyo Night background, the base of the pill and the card
const BASE = '26, 27, 38';
const HOVER_STEP = 0.12;
const OPEN_STEP = 0.18;

const round2 = n => Math.round(n * 100) / 100;
const clamp = (n, min, max) => Math.min(Math.max(n, min), max);

/**
 * '#rrggbb' in lower case, or null when the value is not a hex colour.
 * @param {unknown} value
 * @returns {string|null}
 */
export function normalizeHex(value) {
    if (typeof value !== 'string')
        return null;
    const hex = value.trim().toLowerCase();
    if (/^#[0-9a-f]{6}$/.test(hex))
        return hex;
    if (/^#[0-9a-f]{3}$/.test(hex))
        return `#${[...hex.slice(1)].map(c => c + c).join('')}`;
    return null;
}

/** @returns {[number, number, number]} */
export function hexToRgb(value) {
    const hex = normalizeHex(value) ?? DEFAULT_ACCENT;
    return [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16));
}

/** GTK colours carry 0 to 1 floats. */
export function rgbaToHex({ red, green, blue }) {
    const byte = v => Math.round(clamp(v, 0, 1) * 255).toString(16).padStart(2, '0');
    return `#${byte(red)}${byte(green)}${byte(blue)}`;
}

/** Pill background alphas for rest, hover and the open calendar, from a percentage. */
export function pillAlphas(percent) {
    const value = Number.isFinite(percent) ? percent : DEFAULT_PILL_OPACITY;
    const rest = clamp(value, MIN_PILL_OPACITY, MAX_PILL_OPACITY) / 100;
    return {
        rest: round2(rest),
        hover: round2(Math.min(1, rest + HOVER_STEP)),
        open: round2(Math.min(1, rest + OPEN_STEP)),
    };
}

/**
 * The override stylesheet. Selectors match stylesheet.css exactly, so this one wins by load order,
 * while the more specific paused and Do Not Disturb rules there still win over it.
 * @param {{accent: unknown, pillOpacity: unknown}} settings
 * @returns {string}
 */
export function themeCss({ accent, pillOpacity }) {
    const hex = normalizeHex(accent) ?? DEFAULT_ACCENT;
    const rgb = hexToRgb(hex).join(', ');
    const tint = alpha => `rgba(${rgb}, ${alpha})`;
    const pill = pillAlphas(Number(pillOpacity));
    const clock = '#panel .panel-button.clock-display';
    return `/* Generated by Island from its settings. */
${clock} .xi-pill { background-color: rgba(${BASE}, ${pill.rest}); }
${clock}:hover .xi-pill { background-color: rgba(${BASE}, ${pill.hover}); }
${clock}:active .xi-pill,
${clock}:checked .xi-pill { background-color: rgba(${BASE}, ${pill.open}); border-color: ${tint(0.65)}; }
${clock} .xi-pill .messages-indicator { color: ${hex}; }
.xi-art { background-color: ${tint(0.22)}; }
.xi-art-icon { color: ${hex}; }
.xi-meter-bar { background-color: ${hex}; }
.xi-card-art { background-color: ${tint(0.16)}; }
.xi-card-art-icon { color: ${hex}; }
.xi-card-app { color: ${hex}; }
.xi-control.xi-control-play { color: ${hex}; background-color: ${tint(0.16)}; }
.xi-control.xi-control-play:hover { background-color: ${tint(0.28)}; }
.xi-control:focus,
.xi-card-head:focus { box-shadow: inset 0 0 0 2px ${tint(0.65)}; }
`;
}
